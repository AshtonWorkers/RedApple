"""Deterministic Markdown rendering for submission packets."""

from __future__ import annotations

from .models import REPORT_SCHEMA, SubmissionPacket, packet_sha256
from .redact import redact_text


def _text(value: str, *, fallback: str = "Not established.") -> str:
    cleaned = redact_text(value).strip()
    return cleaned or fallback


def _line(value: str, *, fallback: str = "Not established.") -> str:
    return " ".join(_text(value, fallback=fallback).split())


def _multiline(value: str, *, fallback: str = "Not established.") -> str:
    return _text(value, fallback=fallback)


def render_report_markdown(packet: SubmissionPacket) -> str:
    """Render a packet to a stable Markdown report."""
    lines: list[str] = [
        "# Apple Security Bounty Submission",
        "",
        f"- Report schema: `{REPORT_SCHEMA}`",
        f"- Packet schema: `{packet.schema}`",
        f"- Packet ID: `{packet.packet_id}`",
        f"- Packet SHA-256: `{packet_sha256(packet)}`",
        f"- Source claim: `{packet.claim_id}` (`{packet.claim_type}`)",
        f"- Claim confidence: `{packet.confidence:.3f}`",
        f"- Claim created: `{packet.created}`",
        f"- Run ID: `{packet.run_id or 'none'}`",
        f"- Dedup key: `{packet.dedup_key}`",
        "",
        "## Summary",
        "",
        _line(packet.title, fallback="Untitled promoted finding"),
        "",
        "## Affected Component and Surface",
        "",
        f"- Component: {_line(packet.component)}",
        f"- Surface: {_line(packet.surface)}",
        "",
        "## Root Cause",
        "",
        _multiline(packet.root_cause),
        "",
        "## Reproduction Steps",
        "",
    ]
    if packet.repro_steps:
        for index, step in enumerate(packet.repro_steps, start=1):
            lines.append(f"{index}. {_line(step)}")
    else:
        lines.append("1. Not established.")
    lines.extend(
        [
            "",
            "## Crash Signature",
            "",
            "```text",
            _line(packet.crash_signature, fallback="unknown"),
            "```",
            "",
            "## Exploitability and Impact",
            "",
            "### Exploitability",
            "",
            _multiline(packet.exploitability),
            "",
            "### Impact",
            "",
            _multiline(packet.impact),
            "",
            "## Chain and Escalation",
            "",
            "### Chain",
            "",
            _multiline(packet.chain_summary),
            "",
            "### Escalation",
            "",
            _multiline(packet.escalation_summary),
            "",
            "## Bounty Tier Estimate",
            "",
            f"- Tier: `{packet.bounty_tier}`",
            "",
            _multiline(packet.bounty_rationale),
            "",
            "## Evidence",
            "",
        ]
    )
    if packet.evidence:
        for item in packet.evidence:
            lines.append(
                f"- `{redact_text(item.artifact_id)}` kind=`{redact_text(item.kind)}` "
                f"role=`{redact_text(item.role)}` sha256=`{redact_text(item.sha256)}` "
                f"bytes=`{item.byte_size}` ttl=`{redact_text(item.ttl_class)}` "
                f"created=`{item.created}`"
            )
    else:
        lines.append("- No artifact metadata available.")
    lines.extend(["", "## Warnings", ""])
    if packet.warnings:
        for warning in packet.warnings:
            lines.append(f"- {_line(warning)}")
    else:
        lines.append("- None.")
    lines.extend(["", "---", "", "Deterministic report generated by RedApple `ra.submit`.", ""])
    return "\n".join(lines)


__all__ = ["render_report_markdown"]
